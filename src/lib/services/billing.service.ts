// src/lib/services/billing.service.ts
// ─────────────────────────────────────────────────────────────────────────────
// BILLING: The core operation this entire system was built for.
//
// TWO PUBLIC FUNCTIONS:
//
// lookupMemberByCard(cardNumber)
//   → finds card → member + wallet → computes readiness
//   → used by the billing UI before the cashier selects items
//
// createBill(input, actorId)
//   → THE ATOMIC BILLING OPERATION:
//   1. Validate inputs
//   2. Find card, member, wallet
//   3. Readiness gate (all 6 conditions must pass)
//   4. Fetch products + stock for all items
//   5. Build bill items with SNAPSHOT prices from DB
//   6. Verify balance sufficient + stock sufficient (pre-flight)
//   7. START TRANSACTION:
//      a. Create Bill document
//      b. Deduct wallet with $gte balance guard
//      c. Deduct stock per item with $gte qty guard
//      d. Create Transaction record
//      e. Create StockMovement per item
//   8. COMMIT
//
// If anything inside the transaction throws, ALL writes are rolled back.
//
// MODEL FIELD REFERENCE (what the actual Mongoose schemas use):
//   Stock:         currentQty         (NOT currentQuantity)
//   Transaction:   balanceBefore      (NOT walletBalanceBefore)
//                  balanceAfter       (NOT walletBalanceAfter)
//                  NO referenceId / referenceModel fields
//   StockMovement: movementType       (NOT type)
//                  quantityChanged    (NOT quantity)
//                  quantityBefore     (NOT balanceBefore)
//                  notes: string      (NOT null - must be string)
//   Bill:          subtotal on items  (NOT lineTotal)
//                  walletId required
//                  billNumber auto-generated by pre-save hook
// ─────────────────────────────────────────────────────────────────────────────

